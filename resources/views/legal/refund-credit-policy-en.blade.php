<p class="page-description">This Policy explains the use of credits, paid subscriptions, refunds, and cancellations for the AI consultation service provided by Art Full Stack (“we,” “us,” or “our”).</p>

<section class="legal-section">
    <h2>1. Credits</h2>
    <p>“Credits” are units used within the Service to access AI-generated consultation responses.</p>
    <p>Guests may use one free trial consultation. Free accounts receive one consultation per day, and the Lite plan generally consumes one credit for each consultation. The Premium plan does not consume daily credits and has no daily consultation limit.</p>
    <p>The number of credits granted and the applicable conditions are shown on the plans and pricing page. You can check your balance in the Service.</p>
</section>

<section class="legal-section">
    <h2>2. Expiration and Order of Use</h2>
    <h3>2.1 Daily Credits</h3>
    <p>Free accounts receive one daily credit. Unused daily credits do not carry over. The guest trial is available once.</p>
    <p>The Lite plan receives ten daily credits, with unused credits carried over up to a maximum balance of 50. The Premium plan has no daily consultation limit, but consecutive use is limited to five consultations per minute.</p>
    <p>The Service’s displayed terms govern how daily credits are handled when you change plans.</p>
    <h3>2.2 Balance and Usage History</h3>
    <p>Displayed balances are based on system records and may be temporarily delayed due to communication failures or other circumstances.</p>
</section>

<section class="legal-section">
    <h2>3. Refunds and Cancellations</h2>
    <h3>3.1 After Using a Credit</h3>
    <p>After a credit has been used to receive a consultation response, we generally do not provide a refund because the response did not meet your expectations or for similar reasons.</p>
    <p>If a system failure or similar issue prevents the Service from being provided properly, we may review the circumstances and restore the credit or otherwise address the issue.</p>
    <h3>3.2 Duplicate Payments</h3>
    <p>If we confirm an unintended duplicate payment for the same item or plan, we will refund the duplicate amount or take another appropriate measure.</p>
    <p>The method and timing of a refund may depend on the payment method and payment provider.</p>
    <h3>3.3 Service Disruptions</h3>
    <p>If a system failure or other cause attributable to us prevents normal use of a paid plan, we will review the circumstances and respond reasonably, such as by adjusting the service period or providing a refund.</p>
    <p>Disruptions caused by your device, network, browser settings, or other circumstances on your side may not be eligible for a refund.</p>
    <h3>3.4 Refund Requests</h3>
    <p>If you would like us to investigate a refund or payment issue, contact us as soon as reasonably possible after it occurs. Please provide:</p>
    <ul>
        <li>The email address registered to your account;</li>
        <li>The plan you subscribed to;</li>
        <li>A description of the issue;</li>
        <li>Information shown on the Stripe or other payment page, if needed; and</li>
        <li>The payment amount.</li>
    </ul>
    <p>We will determine whether a refund is appropriate after reviewing the payment information.</p>
</section>

<section class="legal-section">
    <h2>4. Canceling a Paid Plan</h2>
    <h3>4.1 How to Cancel</h3>
    <p>You may cancel the Lite or Premium plan through account settings after signing in or through the Stripe Customer Portal. Follow the instructions in the Service.</p>
    <h3>4.2 Effect of Cancellation</h3>
    <p>Cancellation generally stops the next renewal. You may continue using your plan until the end of the current billing period.</p>
    <p>We generally do not provide prorated refunds for the unused portion of a billing period when you cancel mid-period.</p>
    <h3>4.3 Next Billing Date</h3>
    <p>If cancellation is not completed before the next renewal date, the plan renews automatically and the applicable fee will be charged. Check your renewal date and cancel in advance if you do not wish to renew.</p>
    <h3>4.4 Changing Plans</h3>
    <p>If plan changes are available, the conditions, effective date, and fees shown during the purchase or change process apply. Review any price difference and other conditions displayed at that time.</p>
</section>

<section class="legal-section">
    <h2>5. If the Service Ends</h2>
    <p>If we terminate the Service, we will announce this in the Service in advance where reasonably possible.</p>
    <p>We will provide separate information, as appropriate, about any remaining paid subscription period, taking into account the reason and timing of termination and other circumstances.</p>
</section>

<section class="legal-section">
    <h2>6. Payments</h2>
    <p>Payments for paid plans are processed through Stripe or another payment service. Card details required for payment are generally processed through the payment provider’s systems rather than directly collected or stored by us.</p>
    <p>See the applicable payment provider’s terms and privacy policy for details about payment processing.</p>
</section>

<section class="legal-section">
    <h2>7. Contact</h2>
    <p>For questions about credits, refunds, payments, or cancellations, contact us using the contact details in the Service. We may ask for your registered email address, plan, or other information to verify your identity and subscription.</p>
    <p>We will review your payment and usage information when responding to refund inquiries.</p>
</section>

<section class="legal-section">
    <h2>8. Changes to This Policy</h2>
    <p>We may change this Policy due to changes in law, the Service, or other circumstances. We will announce material changes through an appropriate method in the Service.</p>
</section>
