<p class="page-description">Art Full Stack（以下「当事業者」といいます。）が提供するタロット占いサービス（以下「本サービス」といいます。）における、クレジットの利用、有料プランの契約、返金およびキャンセルについて、以下のとおり定めます。</p>

<section class="legal-section">
    <h2>1. クレジットの内容</h2>
    <p>本サービスにおける「クレジット」は、AIによるタロットリーディングを利用するために使用できるサービス内の利用単位です。</p>
    <p>原則として、1回のタロットリーディングにつき1クレジットを消費します。</p>
    <p>クレジットの付与数、販売価格および利用条件については、購入時の画面および本サービス内の料金・プランページに表示します。</p>
    <p>購入したクレジットは、現金への換金、払い戻し、他の利用者への譲渡または販売をすることはできません。</p>
    <p>クレジットの残高は、無料利用または有料プランに応じて日々付与される「日次クレジット」と、購入により付与される「購入クレジット」に分けて管理します。</p>
</section>

<section class="legal-section">
    <h2>2. クレジットの有効期限・利用順序</h2>
    <h3>2.1 購入クレジット</h3>
    <p>購入したクレジットには、原則として有効期限を設けません。</p>
    <p>ただし、本サービスの終了その他やむを得ない事情により利用できなくなる場合には、別途、本サービス上でお知らせします。</p>
    <h3>2.2 日次クレジット</h3>
    <p>無料利用では、日次クレジットが毎日3回分まで補充されます。未使用分は翌日以降に繰り越されません。</p>
    <p>ライトプランでは毎日5回分、プレミアムプランでは毎日10回分の日次クレジットが補充されます。有料プランの日次クレジットは未使用分を翌日以降に繰り越し、それぞれ最大150回分、最大300回分まで保有できます。</p>
    <p>プランの変更等に伴う日次クレジットの取扱いは、本サービス上の表示に従います。</p>
    <h3>2.4 クレジットの利用順序</h3>
    <p>タロットリーディングを利用する際は、日次クレジットを先に消費し、日次クレジットが不足している場合に購入クレジットを消費します。</p>
    <h3>2.5 クレジット残高・利用履歴</h3>
    <p>本サービス内で、日次クレジットおよび購入クレジットの残高を確認できます。</p>
    <p>なお、表示される残高はシステム上の記録に基づくものであり、通信障害その他の事情により一時的に表示が遅れる場合があります。</p>
</section>

<section class="legal-section">
    <h2>3. 返金・キャンセル</h2>
    <h3>3.1 クレジット購入</h3>
    <p>購入済みのクレジットについては、購入者の都合による返金、キャンセルまたは現金への払い戻しには、原則として応じていません。</p>
    <p>購入前に、購入するクレジット数、料金および利用条件をご確認ください。</p>
    <p>ただし、以下の場合はこの限りではありません。</p>
    <ul>
        <li>同一のクレジットについて、明らかな重複決済が発生した場合</li>
        <li>当事業者側のシステム障害等により、決済後にクレジットが正常に付与されなかった場合</li>
        <li>当事業者の責めに帰すべき事由により、購入したクレジットを利用できない場合</li>
        <li>その他、当事業者が返金相当と判断した場合</li>
    </ul>
    <h3>3.2 クレジットを使用した後の返金</h3>
    <p>クレジットを使用してタロットリーディングの提供を受けた後は、リーディング結果の内容、期待と異なる、占い結果に納得できない等の理由による返金には、原則として応じていません。</p>
    <p>ただし、システム障害等により、正常なサービス提供が行われなかった場合には、状況を確認したうえで、クレジットの再付与その他の方法により対応する場合があります。</p>
    <h3>3.3 重複決済</h3>
    <p>同一の商品またはプランについて、利用者の意図しない重複決済が確認された場合は、重複分について返金その他適切な方法で対応します。</p>
    <p>返金方法および返金時期は、決済方法および決済事業者の処理状況等により異なる場合があります。</p>
    <h3>3.4 サービス障害等</h3>
    <p>当事業者側のシステム障害その他当事業者の責めに帰すべき事由により、購入したクレジットまたは有料プランを正常に利用できなかった場合は、状況を確認したうえで、クレジットの再付与、利用期間の調整、返金その他合理的な方法により対応します。</p>
    <p>一時的な通信障害、利用者の端末・通信環境、ブラウザの設定その他利用者側の環境に起因する場合は、返金の対象とならない場合があります。</p>

    <h3>3.5 返金申請</h3>
    <p>返金または購入に関する調査を希望する場合は、購入後または問題の発生後、できるだけ速やかにお問い合わせください。</p>

    <p>お問い合わせの際には、以下の情報をご提示ください。</p>

    <ul>
        <li>登録メールアドレス</li>
        <li>購入日時</li>
        <li>購入した商品またはプラン</li>
        <li>発生した問題の内容</li>
        <li>Stripe等の決済画面で確認できる情報（必要な場合）</li>
        <li>決済金額</li>
    </ul>
    <p>決済情報を確認したうえで、返金の可否を判断します。</p>
</section>

<section class="legal-section">
    <h2>4. 有料プランの解約</h2>
    <h3>4.1 解約方法</h3>
    <p>LightプランおよびPremiumプランの解約は、ログイン後のアカウント設定またはStripeのカスタマーポータルから手続きできます。</p>
    <p>解約手続きの具体的な方法は、本サービス内の案内に従ってください。</p>
    <h3>4.2 解約の効力</h3>
    <p>有料プランの解約手続きを行った場合、原則として次回の更新を停止する形で解約されます。</p>
    <p>解約手続き後も、現在の契約期間が終了するまでは、契約中のプランを利用できます。</p>
    <p>契約期間の途中で解約した場合であっても、未利用期間に対応する料金の日割り返金は、原則として行いません。</p>
    <h3>4.3 次回請求</h3>
    <p>次回の更新日前に解約手続きが完了していない場合、次回の契約期間について自動的に更新され、所定の料金が請求されます。</p>
    <p>解約を希望する場合は、次回更新日を確認のうえ、余裕をもって手続きを行ってください。</p>
    <h3>4.4 プラン変更</h3>
    <p>LightプランとPremiumプランの変更が可能な場合、その変更条件、適用時期および料金については、購入・変更画面に表示される内容に従います。</p>
    <p>プラン変更によって発生する差額、クレジットの取扱いその他の条件については、変更手続き時に表示される内容をご確認ください。</p>
</section>

