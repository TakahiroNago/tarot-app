<section class="legal-section">
    <h2>1. クレジットの内容</h2>
    <p>本サービスにおける「クレジット」は、AIによるタロットリーディングを利用するために使用できるサービス内の利用単位です。</p>
    <p>無料利用およびライトプランでは、原則として1回のタロットリーディングにつき1クレジットを消費します。プレミアムプランでは日次クレジットを消費せず、占い回数に日次上限はありません。</p>
    <p>クレジットの付与数および利用条件については、本サービス内の料金・プランページに表示します。</p>
    <p>クレジットの残高は、本サービス内で確認できます。</p>
</section>

<section class="legal-section">
    <h2>2. クレジットの有効期限・利用順序</h2>
    <h3>2.1 日次クレジット</h3>
    <p>無料利用では、日次クレジットが毎日3回分まで補充されます。未使用分は翌日以降に繰り越されません。</p>
    <p>ライトプランでは毎日10回分の日次クレジットが補充され、未使用分は翌日以降に繰り越して最大50回分まで保有できます。プレミアムプランでは占い回数に日次上限はありませんが、短時間での連続利用は1分あたり5回までに制限されます。</p>
    <p>プランの変更等に伴う日次クレジットの取扱いは、本サービス上の表示に従います。</p>
    <h3>2.2 クレジット残高・利用履歴</h3>
    <p>なお、表示される残高はシステム上の記録に基づくものであり、通信障害その他の事情により一時的に表示が遅れる場合があります。</p>
</section>

<section class="legal-section">
    <h2>3. 返金・キャンセル</h2>
    <h3>3.1 クレジットを使用した後の返金</h3>
    <p>クレジットを使用してタロットリーディングの提供を受けた後は、リーディング結果の内容、期待と異なる、占い結果に納得できない等の理由による返金には、原則として応じていません。</p>
    <p>ただし、システム障害等により、正常なサービス提供が行われなかった場合には、状況を確認したうえで、クレジットの再付与その他の方法により対応する場合があります。</p>
    <h3>3.2 重複決済</h3>
    <p>同一の商品またはプランについて、利用者の意図しない重複決済が確認された場合は、重複分について返金その他適切な方法で対応します。</p>
    <p>返金方法および返金時期は、決済方法および決済事業者の処理状況等により異なる場合があります。</p>
    <h3>3.3 サービス障害等</h3>
    <p>当事業者側のシステム障害その他当事業者の責めに帰すべき事由により、有料プランを正常に利用できなかった場合は、状況を確認したうえで、利用期間の調整、返金その他合理的な方法により対応します。</p>
    <p>一時的な通信障害、利用者の端末・通信環境、ブラウザの設定その他利用者側の環境に起因する場合は、返金の対象とならない場合があります。</p>

    <h3>3.4 返金申請</h3>
    <p>返金または決済に関する調査を希望する場合は、問題の発生後、できるだけ速やかにお問い合わせください。</p>

    <p>お問い合わせの際には、以下の情報をご提示ください。</p>

    <ul>
        <li>登録メールアドレス</li>
        <li>契約したプラン</li>
        <li>発生した問題の内容</li>
        <li>Stripe等の決済画面で確認できる情報（必要な場合）</li>
        <li>決済金額</li>
