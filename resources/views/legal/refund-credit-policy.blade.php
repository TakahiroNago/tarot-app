    <p>決済情報を確認したうえで、返金の可否を判断します。</p>
</section>

<section class="legal-section">
    <h2>4. 有料プランの解約</h2>
    <h3>4.1 解約方法</h3>
    <p>ライトプランおよびプレミアムプランの解約は、ログイン後のアカウント設定またはStripeのカスタマーポータルから手続きできます。</p>
    <p>解約手続きの具体的な方法は、本サービス内の案内に従ってください。</p>
    <h3>4.2 解約の効力</h3>
    <p>有料プランの解約手続きを行った場合、原則として次回の更新を停止する形で解約されます。</p>
    <p>解約手続き後も、現在の契約期間が終了するまでは、契約中のプランを利用できます。</p>
    <p>契約期間の途中で解約した場合であっても、未利用期間に対応する料金の日割り返金は、原則として行いません。</p>
    <h3>4.3 次回請求</h3>
    <p>次回の更新日前に解約手続きが完了していない場合、次回の契約期間について自動的に更新され、所定の料金が請求されます。</p>
    <p>解約を希望する場合は、次回更新日を確認のうえ、余裕をもって手続きを行ってください。</p>
    <h3>4.4 プラン変更</h3>
    <p>ライトプランとプレミアムプランの変更が可能な場合、その変更条件、適用時期および料金については、購入・変更画面に表示される内容に従います。</p>
    <p>プラン変更によって発生する差額その他の条件については、変更手続き時に表示される内容をご確認ください。</p>
</section>

